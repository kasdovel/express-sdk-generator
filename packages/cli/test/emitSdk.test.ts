import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { emitSdk } from '../src/emitSdk.js';

const DOC = {
  openapi: '3.1.0',
  info: { title: 'T', version: '1' },
  paths: {
    '/users/{id}': {
      get: {
        operationId: 'getUser',
        parameters: [{ name: 'id', in: 'path', required: true, schema: { type: 'string' } }],
        responses: {
          200: {
            description: 'OK',
            content: { 'application/json': { schema: { type: 'object' } } },
          },
        },
      },
    },
  },
};

let dir: string;
beforeAll(async () => {
  dir = await mkdtemp(join(tmpdir(), 'sdkgen-sdk-'));
});
afterAll(async () => {
  await rm(dir, { recursive: true, force: true });
});

describe('emitSdk', () => {
  it('marks every emitted file as generated', async () => {
    const out = await emitSdk(DOC, { out: 'sdk' }, dir);
    for (const file of ['client.ts', 'schemas.ts', 'types.ts', 'runtime.ts', 'index.ts']) {
      const src = await readFile(join(out, file), 'utf8');
      expect(src.startsWith('/* eslint-disable */\n// @generated by sdkgen')).toBe(true);
    }
  });

  it('rejects an operationId that would shadow a BaseClient member', async () => {
    const doc = {
      paths: {
        '/x': {
          get: { operationId: 'request', responses: { 200: { description: 'OK' } } },
        },
      },
    };
    await expect(emitSdk(doc, { out: 'sdk-clash' }, dir)).rejects.toThrow(
      /collides with a member of the generated client/,
    );
  });
});
